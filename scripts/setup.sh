#!/usr/bin/env bash
# One-time, offline. Produces the proving key, the verification key and the
# Solidity verifier. Everything here maps to a chapter of the course.
set -euo pipefail
cd "$(dirname "$0")/.."

CIRCOM=./bin/circom
SNARKJS="npx snarkjs"
POWER=12          # 2^12 = 4096 >= 1333 constraints
B=build

say() { printf "\n\033[1m%s\033[0m\n" "$1"; }

say "1/5  compile the circuit   (Ch 12-13: code -> R1CS)"
$CIRCOM circuits/agegate.circom --r1cs --wasm --sym -l node_modules -l circuits -o $B
$SNARKJS r1cs info $B/agegate.r1cs

say "2/5  powers of tau         (Ch 15: the universal ceremony)"
# DEMO ONLY. Production must reuse the Perpetual Powers of Tau transcript --
# a ptau you generated yourself is a ptau whose toxic waste you know.
$SNARKJS powersoftau new bn128 $POWER $B/pot_0000.ptau -v > /dev/null
$SNARKJS powersoftau contribute $B/pot_0000.ptau $B/pot_0001.ptau \
  --name="demo contribution" -v -e="$(head -c 64 /dev/urandom | base64)" > /dev/null
$SNARKJS powersoftau prepare phase2 $B/pot_0001.ptau $B/pot_final.ptau -v > /dev/null

say "3/5  circuit-specific setup (Ch 15: phase 2, per-circuit for Groth16)"
$SNARKJS groth16 setup $B/agegate.r1cs $B/pot_final.ptau $B/agegate_0000.zkey > /dev/null
$SNARKJS zkey contribute $B/agegate_0000.zkey $B/agegate_final.zkey \
  --name="demo contribution" -v -e="$(head -c 64 /dev/urandom | base64)" > /dev/null

say "4/5  export the verification key"
$SNARKJS zkey export verificationkey $B/agegate_final.zkey $B/vkey.json > /dev/null

say "5/5  generate Verifier.sol  (Ch 17: alpha, beta, gamma, delta hardcoded)"
$SNARKJS zkey export solidityverifier $B/agegate_final.zkey contracts/src/Verifier.sol
# The generated contract is named Groth16Verifier; give it the interface our gate expects.
printf '\n// Generated by snarkjs from agegate_final.zkey. Do not edit by hand.\n' >> contracts/src/Verifier.sol

say "done"
ls -lh $B/agegate_final.zkey $B/vkey.json contracts/src/Verifier.sol | awk '{printf "  %-46s %s\n", $9, $5}'
printf "\n  merkle root (publish this): %s\n\n" "$(node -e 'console.log(JSON.parse(require("fs").readFileSync("build/root.json")).root)')"
