/**
 * Generates contracts/test/Fixtures.sol — real Groth16 proofs baked into
 * Solidity constants so `forge test` can run without a node toolchain.
 *
 * Produces four fixtures:
 *   honest1  roll 1, age 19  -> should enroll
 *   honest5  roll 5, age 21  -> should enroll
 *   rogue9   roll 9, age 15 but issued by a ROGUE registrar who wrote 18
 *            -> a perfectly valid proof against the WRONG root
 *   lowBar1  roll 1 proved against threshold = 1 instead of 18
 *            -> valid proof, wrong statement
 */
import fs from "fs";
import * as snarkjs from "snarkjs";
import { buildTree } from "../registry/tree-lib.js";

const B = "build";
const WASM = `${B}/agegate_js/agegate.wasm`;
const ZKEY = `${B}/agegate_final.zkey`;

const registry = JSON.parse(fs.readFileSync("registry/students.json", "utf8")).students;
const realRoot = JSON.parse(fs.readFileSync(`${B}/root.json`, "utf8")).root;

const prove = async (input, label) => {
  const { proof, publicSignals } = await snarkjs.groth16.fullProve(input, WASM, ZKEY);
  const ok = await snarkjs.groth16.verify(JSON.parse(fs.readFileSync(`${B}/vkey.json`)), publicSignals, proof);
  console.log(`  ${label.padEnd(9)} proof ok=${ok}  root=${publicSignals[0].slice(0, 12)}…  roll=${publicSignals[1]}  threshold=${publicSignals[2]}`);
  return { proof, publicSignals };
};

const sol = (name, { proof, publicSignals }) => `
    function ${name}() internal pure returns (Proof memory) {
        return Proof({
            a: [uint256(${proof.pi_a[0]}), uint256(${proof.pi_a[1]})],
            b: [
                [uint256(${proof.pi_b[0][1]}), uint256(${proof.pi_b[0][0]})],
                [uint256(${proof.pi_b[1][1]}), uint256(${proof.pi_b[1][0]})]
            ],
            c: [uint256(${proof.pi_c[0]}), uint256(${proof.pi_c[1]})],
            root: ${publicSignals[0]},
            rollNumber: ${publicSignals[1]},
            threshold: ${publicSignals[2]}
        });
    }
`;

console.log("\n  generating fixtures\n");

// --- honest students ------------------------------------------------------
const honest1 = await prove(JSON.parse(fs.readFileSync(`${B}/bundles/1.json`)), "honest1");
const honest5 = await prove(JSON.parse(fs.readFileSync(`${B}/bundles/5.json`)), "honest5");

// --- a rogue registrar lies about Arjun's age -----------------------------
// The circuit is satisfied: the leaf really does say 18, and the path really
// does reach THIS tree's root. But it is not the root the course trusts.
const tampered = registry.map((s) => (s.roll === 9 ? { ...s, age: 18 } : s));
const { root: rogueRoot, bundles: rogueBundles } = await buildTree(tampered);
console.log(`  rogue root differs from real root: ${rogueRoot.toString() !== realRoot}`);
const rogue9 = await prove(rogueBundles[9], "rogue9");

// --- a student proves against a threshold of 1 ----------------------------
const lowBarInput = { ...JSON.parse(fs.readFileSync(`${B}/bundles/1.json`)), threshold: "1" };
const lowBar1 = await prove(lowBarInput, "lowBar1");

const out = `// SPDX-License-Identifier: MIT
// GENERATED by scripts/gen-fixtures.js — do not edit.
// Every proof below is a real Groth16 proof produced by snarkjs.
pragma solidity ^0.8.20;

contract Fixtures {
    struct Proof {
        uint256[2] a;
        uint256[2][2] b;
        uint256[2] c;
        uint256 root;
        uint256 rollNumber;
        uint256 threshold;
    }

    uint256 internal constant REAL_ROOT = ${realRoot};
${sol("honest1", honest1)}${sol("honest5", honest5)}${sol("rogue9", rogue9)}${sol("lowBar1", lowBar1)}}
`;

fs.mkdirSync("contracts/test", { recursive: true });
fs.writeFileSync("contracts/test/Fixtures.sol", out);
console.log(`\n  -> contracts/test/Fixtures.sol\n`);
process.exit(0);
